; Main 60 FPS Animation Loop
frame_loop:
    MOVI r30, 16384    ; Pointer to star 0
    MOVI r28, 64       ; Star count
    MOVI r27, 1        ; Decrement 1
    MOVI r26, 8        ; Word stride 8
    MOVI r25, 72       ; Next star offset (9 * 8 bytes)
    MOVI r20, 160      ; Center X
    MOVI r21, 100      ; Center Y

star_loop:
    BEQ r28, zero, sync_frame

    MOV r15, r30
    LOAD r1, r15
    ADD r15, r15, r26
    LOAD r2, r15
    ADD r15, r15, r26
    LOAD r3, r15
    ADD r15, r15, r26
    LOAD r4, r15
    ADD r15, r15, r26
    LOAD r5, r15
    ADD r15, r15, r26
    LOAD r6, r15
    ADD r15, r15, r26
    LOAD r7, r15
    ADD r15, r15, r26
    LOAD r8, r15
    ADD r15, r15, r26
    LOAD r9, r15

    ; Erase old star position
    STORE r6, r10      ; PixelX = OldX
    STORE r7, r11      ; PixelY = OldY
    STOREB zero, r12   ; Plot black

    ; Update position: X += Vx, Y += Vy, Life -= 1
    ADD r1, r1, r3
    ADD r2, r2, r4
    SUB r8, r8, r27

    BNE r8, zero, star_alive
    MOV r1, r20        ; Reset X = 160
    MOV r2, r21        ; Reset Y = 100
    MOV r8, r9         ; Reset Life = MaxLife

star_alive:
    ; Plot new star pixel
    STORE r1, r10
    STORE r2, r11
    STOREB r5, r12

    ; Save updated state back
    MOV r15, r30
    STORE r1, r15      ; New X
    ADD r15, r15, r26
    STORE r2, r15      ; New Y
    ADD r15, r15, r26
    ADD r15, r15, r26  ; Skip Vx
    ADD r15, r15, r26  ; Skip Vy
    ADD r15, r15, r26  ; Skip Color
    STORE r1, r15      ; OldX = New X
    ADD r15, r15, r26
    STORE r2, r15      ; OldY = New Y
    ADD r15, r15, r26
    STORE r8, r15      ; Updated Life

    ADD r30, r30, r25  ; r30 += 72 (next star)
    SUB r28, r28, r27  ; r28 -= 1
    JMP star_loop

sync_frame:
    MOVI r1, 16        ; 16 ms sleep -> 60 FPS
    STORE r1, r13
    JMP frame_loop
